
"""
AgriSense-BCTB: Synthetic-label model comparison.

IMPORTANT:
This experiment evaluates reproduction of synthetic scoring labels.
It does NOT establish real-world BCTB prediction accuracy.
"""

from pathlib import Path
import json

import joblib
import numpy as np
import pandas as pd

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler, LabelEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.model_selection import GroupShuffleSplit
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier

try:
    from xgboost import XGBClassifier
except ImportError:
    XGBClassifier = None


# --------------------------------------------------
# 1. PROJECT PATHS
# --------------------------------------------------

ROOT = Path(__file__).resolve().parents[1]

DATA_FILE = ROOT / "data" / "processed" / "agrisense_synthetic_expanded_dataset.csv"

REPORT_DIR = ROOT / "ml" / "reports"
MODEL_DIR = ROOT / "ml" / "models"

REPORT_DIR.mkdir(parents=True, exist_ok=True)
MODEL_DIR.mkdir(parents=True, exist_ok=True)


# --------------------------------------------------
# 2. LOAD DATA
# --------------------------------------------------

df = pd.read_csv(DATA_FILE)

TARGET = "synthetic_demo_risk_band"
GROUP = "farm_id"

# Expanded model inputs. Their labels are generated by an illustrative rule,
# not by verified BCTB outcomes; scores are software demonstrations only.
FEATURES = [
    "twig_dieback_observed",
    "suspected_entry_holes_observed",
    "affected_twig_count_reported",
    "previous_bctb_report",
    "farm_sanitation",
    "pruning_frequency",
    "recent_pruning_done",
    "increasing_twig_damage",
    "yellowing_observed",
    "blackening_observed",
    "wilting_observed",
    "drying_observed",
    "nearby_host_vegetation",
    "unmanaged_suckers_present",
    "recent_desuckering_done",
    "affected_twig_removal",
    "coffee_age",
    "shade_canopy",
    "coffee_variety",
    "affected_twig_diameter_mm",
    "rainfall_30d_mm",
    "mean_temperature_30d_c",
    "mean_relative_humidity_30d_pct",
    "canopy_cover_pct",
    "shade_tree_count",
    "distance_to_woodland_m",
    "drought_stress_observed",
    "recently_transplanted",
    "infested_twigs_removed",
    "coffee_trees_inspected",
    "trees_with_possible_signs",
    "plot_area_ha",
    "shade_tree_species",
    "inspection_month",
]

X = df[FEATURES].copy()
y_text = df[TARGET].copy()
groups = df[GROUP].copy()

print("\nDATASET INFORMATION")
print("-------------------")
print("Records:", len(df))
print("Unique farms:", groups.nunique())
print("\nTarget distribution:")
print(y_text.value_counts())


# --------------------------------------------------
# 3. ENCODE TARGET LABELS
# --------------------------------------------------

label_encoder = LabelEncoder()

y = label_encoder.fit_transform(y_text)

class_names = label_encoder.classes_.tolist()

print("\nClass encoding:")
for index, name in enumerate(class_names):
    print(f"{name} = {index}")


# --------------------------------------------------
# 4. GROUP-AWARE TRAIN/TEST SPLIT
# --------------------------------------------------

splitter = GroupShuffleSplit(
    n_splits=1,
    test_size=0.20,
    random_state=42
)

train_idx, test_idx = next(
    splitter.split(X, y, groups=groups)
)

X_train = X.iloc[train_idx]
X_test = X.iloc[test_idx]

y_train = y[train_idx]
y_test = y[test_idx]

train_groups = set(groups.iloc[train_idx])
test_groups = set(groups.iloc[test_idx])

assert train_groups.isdisjoint(test_groups), (
    "Data leakage: some farms appear in both partitions."
)

print("\nDATA SPLIT")
print("----------")
print("Training records:", len(X_train))
print("Testing records:", len(X_test))
print("Training farms:", len(train_groups))
print("Testing farms:", len(test_groups))
print("Farm overlap:", len(train_groups.intersection(test_groups)))


# --------------------------------------------------
# 5. PREPROCESSING
# --------------------------------------------------

numeric_features = [
    "twig_dieback_observed",
    "suspected_entry_holes_observed",
    "affected_twig_count_reported",
    "previous_bctb_report",
    "recent_pruning_done",
    "increasing_twig_damage",
    "yellowing_observed",
    "blackening_observed",
    "wilting_observed",
    "drying_observed",
    "nearby_host_vegetation",
    "unmanaged_suckers_present",
    "recent_desuckering_done",
    "affected_twig_diameter_mm",
    "rainfall_30d_mm",
    "mean_temperature_30d_c",
    "mean_relative_humidity_30d_pct",
    "canopy_cover_pct",
    "shade_tree_count",
    "distance_to_woodland_m",
    "drought_stress_observed",
    "recently_transplanted",
    "infested_twigs_removed",
    "coffee_trees_inspected",
    "trees_with_possible_signs",
    "plot_area_ha",
    "inspection_month",
]

categorical_features = [
    "farm_sanitation",
    "pruning_frequency",
    "affected_twig_removal",
    "coffee_age",
    "shade_canopy",
    "coffee_variety",
    "shade_tree_species",
]

if len(FEATURES) != len(set(FEATURES)) or set(FEATURES) != set(numeric_features + categorical_features):
    raise ValueError("Every model feature must appear exactly once in the numeric/categorical preprocessing schema.")

numeric_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer([
    ("numeric", numeric_pipeline, numeric_features),
    ("categorical", categorical_pipeline, categorical_features)
])


# --------------------------------------------------
# 6. DEFINE MODELS
# --------------------------------------------------

models = {
    "Logistic Regression": LogisticRegression(
        max_iter=2000,
        class_weight="balanced",
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=300,
        class_weight="balanced",
        random_state=42,
        n_jobs=1
    ),

}

if XGBClassifier is not None:
    models["XGBoost"] = XGBClassifier(
        n_estimators=300,
        max_depth=4,
        learning_rate=0.05,
        objective="multi:softprob",
        num_class=len(class_names),
        eval_metric="mlogloss",
        random_state=42,
        n_jobs=1
    )


# --------------------------------------------------
# 7. TRAIN AND EVALUATE
# --------------------------------------------------

results = []
trained_models = {}

for model_name, classifier in models.items():

    print(f"\nTRAINING: {model_name}")
    print("=" * 50)

    pipeline = Pipeline([
        ("preprocessor", preprocessor),
        ("classifier", classifier)
    ])

    pipeline.fit(X_train, y_train)

    predictions = pipeline.predict(X_test)

    accuracy = accuracy_score(y_test, predictions)

    precision = precision_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        average="macro",
        zero_division=0
    )

    results.append({
        "model": model_name,
        "accuracy": accuracy,
        "macro_precision": precision,
        "macro_recall": recall,
        "macro_f1": f1
    })

    trained_models[model_name] = pipeline

    print(f"Accuracy:  {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall:    {recall:.4f}")
    print(f"Macro F1:  {f1:.4f}")

    print("\nClassification report:")
    print(
        classification_report(
            y_test,
            predictions,
            labels=np.arange(len(class_names)),
            target_names=class_names,
            zero_division=0
        )
    )

    matrix = confusion_matrix(
        y_test,
        predictions,
        labels=np.arange(len(class_names))
    )

    matrix_df = pd.DataFrame(
        matrix,
        index=[f"Actual_{name}" for name in class_names],
        columns=[f"Predicted_{name}" for name in class_names]
    )

    matrix_df.to_csv(
        REPORT_DIR / f"{model_name.lower().replace(' ', '_')}_confusion_matrix.csv"
    )

    joblib.dump(
        pipeline,
        MODEL_DIR / f"{model_name.lower().replace(' ', '_')}.joblib"
    )


# --------------------------------------------------
# 8. SAVE MODEL COMPARISON
# --------------------------------------------------

results_df = pd.DataFrame(results)

results_df = results_df.sort_values(
    by="macro_f1",
    ascending=False
)

results_df.to_csv(
    REPORT_DIR / "model_comparison.csv",
    index=False
)

print("\nFINAL MODEL COMPARISON")
print("======================")
print(results_df.to_string(index=False))


# --------------------------------------------------
# 9. SAVE EXPERIMENT METADATA
# --------------------------------------------------

metadata = {
    "experiment": "Expanded synthetic BCTB label classification",
    "dataset_records": int(len(df)),
    "unique_synthetic_farms": int(groups.nunique()),
    "target": TARGET,
    "features": FEATURES,
    "label_generation": "Illustrative synthetic rule over simulated signs, management, weather, and farm context; not verified BCTB outcomes.",
    "training_records": int(len(X_train)),
    "testing_records": int(len(X_test)),
    "training_farms": int(len(train_groups)),
    "testing_farms": int(len(test_groups)),
    "farm_overlap": 0,
    "class_names": class_names,
    "random_state": 42,
    "warning": (
        "Synthetic-label classification only. "
        "Not validated real-world BCTB prediction."
    )
}

with open(
    REPORT_DIR / "experiment_metadata.json",
    "w",
    encoding="utf-8"
) as file:
    json.dump(metadata, file, indent=4)

print("\nExperiment completed.")
print("Reports saved in:", REPORT_DIR)
print("Models saved in:", MODEL_DIR)
